package kutubxona_catalog_service.demo.stage15;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.output.MigrateResult;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;

import java.sql.Timestamp;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * 15-bosqich (17-band): Flyway migratsiyasi ESKI bazaga ham to'g'ri qo'llanadi.
 *
 * Ssenariy: baza avval Hibernate ddl-auto=update bilan yaratilgan (Flyway yo'q edi),
 * books/members/loans jadvallarida audit ustunlari yo'q va ichida ma'lumot bor.
 * Migratsiyadan keyin: yetishmagan ustunlar qo'shiladi, eski ma'lumot saqlanadi.
 */
@Testcontainers
class LegacySchemaMigrationTest {

    @Container
    static PostgreSQLContainer postgres = new PostgreSQLContainer("postgres:16");

    /** Eski (Flyway'dan oldingi) sxema — Hibernate ddl-auto=update yaratgan ko'rinishda. */
    private static final String LEGACY_SCHEMA = """
            create table authors (id bigint generated by default as identity primary key,
                full_name varchar(255) not null, biography varchar(255),
                created_at timestamp(6) not null, updated_at timestamp(6),
                created_by bigint, updated_by bigint, deleted_at timestamp(6), deleted_by bigint);
            create table categories (id bigint generated by default as identity primary key,
                name varchar(255) not null unique,
                created_at timestamp(6) not null, updated_at timestamp(6),
                created_by bigint, updated_by bigint, deleted_at timestamp(6), deleted_by bigint);
            create table books (id bigint generated by default as identity primary key,
                title varchar(255) not null, isbn varchar(255) unique, published_year integer,
                total_copies integer, available_copies integer, price numeric(38,2));
            create table book_authors (book_id bigint not null references books,
                author_id bigint not null references authors, primary key (book_id, author_id));
            create table book_categories (book_id bigint not null references books,
                category_id bigint not null references categories, primary key (book_id, category_id));
            create table members (id bigint generated by default as identity primary key,
                full_name varchar(255) not null, email varchar(255) unique, phone varchar(255));
            create table loans (id bigint generated by default as identity primary key,
                book_id bigint not null references books, member_id bigint not null references members,
                borrowed_date date, due_date date, returned_date date, status varchar(255));

            insert into books (title, total_copies, available_copies) values ('Eski kitob', 2, 1);
            insert into members (full_name, email) values ('Eski a''zo', 'eski@example.com');
            insert into loans (book_id, member_id, borrowed_date, due_date, status)
                values (1, 1, current_date, current_date + 14, 'ACTIVE');
            """;

    @Test
    void migrationAddsMissingColumnsAndKeepsExistingData() {
        var dataSource = new DriverManagerDataSource(
                postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword());
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        for (String sql : LEGACY_SCHEMA.split(";")) {
            if (!sql.isBlank()) jdbc.execute(sql);
        }

        // application.properties'dagi spring.flyway.* sozlamalari bilan bir xil
        MigrateResult result = Flyway.configure()
                .dataSource(dataSource)
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("0")
                .load()
                .migrate();

        assertThat(result.success).isTrue();
        assertThat(result.migrationsExecuted).isGreaterThanOrEqualTo(1);

        // Eski ma'lumot joyida
        assertThat(jdbc.queryForObject("select title from books where id = 1", String.class))
                .isEqualTo("Eski kitob");
        assertThat(jdbc.queryForObject("select count(*) from loans", Integer.class)).isEqualTo(1);

        // Yetishmagan audit ustunlari qo'shildi va eski qatorlar uchun to'ldirildi
        for (String table : new String[]{"books", "members", "loans"}) {
            assertThat(jdbc.queryForObject("select created_at from " + table + " where id = 1", Timestamp.class))
                    .as(table + ".created_at").isNotNull();
            assertThat(jdbc.queryForObject("select deleted_at from " + table + " where id = 1", Timestamp.class))
                    .as(table + ".deleted_at").isNull();
        }
    }

    @Test
    void migrationIsRepeatable_secondRunDoesNothing() {
        var dataSource = new DriverManagerDataSource(
                postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword());
        Flyway flyway = Flyway.configure().dataSource(dataSource)
                .locations("classpath:db/migration")
                .baselineOnMigrate(true).baselineVersion("0").load();

        flyway.migrate();
        assertThat(flyway.migrate().migrationsExecuted).isZero();
    }
}
