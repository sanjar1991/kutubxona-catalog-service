--   1) Bo'sh baza            -> barcha jadvallar yaratiladi.
--   2) Eski baza (Hibernate ddl-auto=update bilan yaratilgan, Flyway yo'q)
--                            -> mavjud jadvallarga tegilmaydi, faqat yetishmagan
--                               ustunlar/indekslar qo'shiladi, ma'lumot saqlanadi.
-- Shuning uchun hamma joyda IF NOT EXISTS ishlatilgan.
