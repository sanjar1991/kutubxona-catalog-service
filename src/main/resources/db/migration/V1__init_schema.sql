CREATE TABLE IF NOT EXISTS authors (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  varchar(255) NOT NULL,
    biography  varchar(255)
);

CREATE TABLE IF NOT EXISTS categories (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  varchar(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS books (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             varchar(255) NOT NULL,
    isbn              varchar(255) UNIQUE,
    published_year    integer,
    total_copies      integer,
    available_copies  integer,
    price             numeric(38, 2)
);

CREATE TABLE IF NOT EXISTS book_authors (
    book_id    bigint NOT NULL REFERENCES books (id),
    author_id  bigint NOT NULL REFERENCES authors (id),
    PRIMARY KEY (book_id, author_id)
);

CREATE TABLE IF NOT EXISTS book_categories (
    book_id      bigint NOT NULL REFERENCES books (id),
    category_id  bigint NOT NULL REFERENCES categories (id),
    PRIMARY KEY (book_id, category_id)
);

CREATE TABLE IF NOT EXISTS members (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  varchar(255) NOT NULL,
    email      varchar(255) UNIQUE,
    phone      varchar(255)
);

CREATE TABLE IF NOT EXISTS loans (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id        bigint NOT NULL REFERENCES books (id),
    member_id      bigint NOT NULL REFERENCES members (id),
    borrowed_date  date,
    due_date       date,
    returned_date  date,
    status         varchar(255)
);

-- ---------------------------------------------------------------------
-- BaseEntity ustunlari (audit + soft delete) — barcha asosiy jadvallarda.
-- Eski bazada books/members/loans'da ular yo'q edi; mavjud qatorlar uchun
-- created_at = now() bilan to'ldiriladi.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['authors', 'categories', 'books', 'members', 'loans'] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS created_at timestamp(6) NOT NULL DEFAULT now()', t);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS updated_at timestamp(6)', t);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS created_by bigint', t);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS updated_by bigint', t);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS deleted_at timestamp(6)', t);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS deleted_by bigint', t);
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------
-- Tez-tez ishlatiladigan so'rovlar uchun indekslar
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_loans_member_status ON loans (member_id, status);
CREATE INDEX IF NOT EXISTS idx_loans_book_status   ON loans (book_id, status);
CREATE INDEX IF NOT EXISTS idx_loans_status_due    ON loans (status, due_date);
